export const OFF_WORDS: readonly string[] = ['off', 'none', 'stop', 'выкл', 'выключить', '0']

const BY_ID = new Map(EXPERTS.map(expert => [expert.id, expert]))

export function expertOf(id: string): Expert {
  const expert = BY_ID.get(id)
  if (expert === undefined) {
    throw new Error(`expert-teams: нет эксперта «${id}»`)
  }

  return expert
}

export function findTeam(word: string): Team | undefined {
  const key = word.trim().toLowerCase()

  return TEAMS.find(team => team.id === key || team.aliases.includes(key))
}

/** Эксперты, которых модель может вызвать субагентами хотя бы в одной команде. */
export function delegatedExperts(): Expert[] {
  const ids = new Set(TEAMS.flatMap(team => team.members))

  return EXPERTS.filter(expert => ids.has(expert.id))
}

export function agentType(id: string): string {
  return `${PLUGIN}:${id}`
}

/** Размер команды вместе с тимлидом: 1 для соло-эксперта. */
export function sizeOf(team: Team): number {
  return 1 + team.members.length
}

