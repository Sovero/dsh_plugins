/** Системный промпт субагента-эксперта. */
export function agentPrompt(expert: Expert): string {
  return `${expert.persona}\n\n${SUBAGENT_RULES}`
}

/** Описание для списка агентов: когда модели стоит звать эксперта. */
export function agentDescription(expert: Expert): string {
  return `${expert.name} команды экспертов: ${expert.summary}. Зови, когда включена команда, в состав которой он входит.`
}

/** Раздел системного промпта на время, пока команда включена. */
export function teamBrief(team: Team): string {
  const lead = expertOf(team.lead)
  const head =
    `# Режим команды экспертов: «${team.title}»\n\n` +
    `Пользователь выбрал команду командой /team ${team.id} и остаётся её заказчиком. ` +
    'Режим действует, пока он не выберет другую команду или не наберёт /team off.'

  if (team.members.length === 0) {
    return [
      head,
      `В этом режиме ты работаешь как «${lead.name}», единственный эксперт команды. ${lead.persona}`,
      team.workflow,
      'Отвечай от лица эксперта: по существу, с конкретикой и приоритетами. Если вопрос вне твоей роли, скажи об этом и предложи включить подходящую команду через /team.',
    ].join('\n\n')
  }

  const roster = [
    `- ${lead.name} — это ты, основной поток: ${lead.summary}.`,
    ...team.members.map(id => {
      const member = expertOf(id)

      return `- ${member.name} — subagent_type "${agentType(id)}": ${member.summary}.`
    }),
  ].join('\n')

  const rules = [
    `Ты — ${lead.name} этой команды и отвечаешь за итог. ${lead.persona}`,
    'Остальные эксперты — субагенты. Вызывай их инструментом Agent с указанным subagent_type.',
    'Как работать:',
    '1. Разберись в задаче. Если она тривиальна (вопрос, правка в одну строку), сделай сам: эксперты нужны, когда они дают выигрыш в качестве или скорости.',
    '2. Перед запуском экспертов покажи пользователю план в 3–6 строках: кто что делает и в каком порядке.',
    '3. Независимые части запускай параллельно (несколько вызовов Agent в одном сообщении), зависимые — по очереди, передавая результат в промпт следующего.',
    '4. Субагент не видит этот разговор. В промпт каждому включай цель, контекст и ограничения, что уже решено, пути к файлам и какой результат ждёшь.',
    '5. Не поручай двум экспертам менять одни и те же файлы одновременно. Читают и советуют аналитик, архитектор и специалист по безопасности; код правят остальные.',
    '6. Проверяй результаты: сверяй отчёты с кодом, разрешай противоречия между ролями, не пересказывай отчёты дословно.',
    '7. В конце дай итог от лица команды: что сделано и кто что внёс, что проверено, риски и открытые вопросы. Вклад ролей помечай именем роли.',
  ].join('\n')

  return [head, 'Состав команды:\n' + roster, rules, team.workflow].join('\n\n')
}
