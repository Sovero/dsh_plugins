export const PLUGIN = 'expert-teams'

export type Expert = {
  id: string
  /** Название роли, как его видит пользователь. */
  name: string
  /** За что отвечает, одной строкой. */
  summary: string
  /** Описание роли для модели: на нём строится и субагент, и режим соло. */
  persona: string
  /** Какие инструменты разрешены субагенту; не задано, значит все. */
  tools?: readonly string[]
}

export type Team = {
  id: string
  /** Другие слова, которыми команду можно выбрать: /team разработка. */
  aliases: readonly string[]
  title: string
  summary: string
  /** Эксперт, чью роль играет основной поток (в команде из нескольких это тимлид). */
  lead: string
  /** Субагенты команды; пусто, если эксперт работает один. */
  members: readonly string[]
  /** Порядок работы для этой команды. */
  workflow: string
}

